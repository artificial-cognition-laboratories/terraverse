#!/usr/bin/env python3
"""Stride cycles (cycles.py's JSON) as a C++ header for physics/motion: no file to find at run time, so the wiki builds it too.

  header.py walk.json jog.json run.json sprint.json walk_back.json ... > apps/game/src/physics/motion_cycles.h
  header.py --clips jump.json punch_left.json punch_right.json kick_left.json kick_right.json flying_kick.json > apps/game/src/physics/motion_clips.h
"""
import json, sys
if sys.argv[1] == '--clips':
    # Moves played once (clip.py's JSON), beside the strides: their joints are motion_cycles.h's.
    out = ['// Generated by scripts/motion/header.py --clips. Do not edit. Moves played once, each cut from one take of',
           '// the CMU Graphics Lab Motion Capture Database (mocap.cs.cmu.edu; created with funding from NSF EIA-0196217):',
           '// a jump from 105_39, punches from 143_23, kicks from 143_24, a flying kick from 75_16.',
           '#pragma once', '', '#include "physics/motion_cycles.h"', '', 'namespace physics::cycles {', '',
           'struct Clip', '{', '\tconst char *name;', '\tfloat fps;', '\tint frames;',
           '\tint off, back; // a jump: the frames it leaves the ground, and is back on it (a strike: its first and last)',
           '\tint hit;       // a strike: the frame it lands; a jump\'s, -1',
           '\tfloat pace;    // legs/s it went, in the air', '\tconst float (*at)[JOINTS][3]; // against the hips, as a Cycle\'s',
           '\tconst bool (*down)[2];', '};', '']
    for c in [json.load(open(p)) for p in sys.argv[2:]]:
        n, up = len(c['frames']), c['name'].upper()
        rows = ',\n'.join('\t{ ' + ', '.join('{ %.4ff, %.4ff, %.4ff }' % tuple(j) for j in f) + ' }' for f in c['frames'])
        down = ', '.join('{ %s, %s }' % tuple('true' if d else 'false' for d in f) for f in c['down'])
        out += ['constexpr float %s_AT[%d][JOINTS][3]{\n%s };' % (up, n, rows), 'constexpr bool %s_DOWN[%d][2]{ %s };' % (up, n, down),
                'constexpr Clip %s{ "%s", %.1ff, %d, %d, %d, %d, %.4ff, %s_AT, %s_DOWN };' % (up, c['name'], c['fps'], n, c['off'], c['back'], c.get('hit', -1), c['pace'], up, up), '']
    out += ['} // namespace physics::cycles', '']
    print('\n'.join(out))
    sys.exit()
clips = [json.load(open(p)) for p in sys.argv[1:]]
names = clips[0]['joints']
out = ['// Generated by scripts/motion/header.py. Do not edit. Each averaged into one stride:',
       '// walks and jogs, ahead, back and to each side, and crouched, from 100STYLE (Ian Mason, CC BY 4.0:',
       '// ianxmason.com/100style), its Neutral and Crouched styles;',
       '// run and sprint from the CMU Graphics Lab Motion Capture Database (mocap.cs.cmu.edu; created with funding',
       '// from NSF EIA-0196217), subject 9\'s runs and 102_05, 127_07 and 127_08.', '#pragma once', '',
       'namespace physics::cycles {', '',
       'enum Joint { ' + ', '.join(n.upper() for n in names) + ', JOINTS };',
       'constexpr int PHASES = %d;' % len(clips[0]['phases']), '',
       'struct Cycle', '{', '\tconst char *name;', '\tfloat pace;   // legs/s', '\tfloat period; // s a stride',
       '\tint strides;  // averaged', '\tfloat way;    // degrees it went, against the way it faced: 0 ahead, 90 its right', '\tfloat at[PHASES][JOINTS][3]; // against the hips, in legs: x right, y up, z ahead (the hips\' own: y their height)',
       '\tbool down[PHASES][2];        // each foot on the ground, right then left: low and still, in most of its strides', '};', '']
for c in clips:
    rows = ',\n'.join('\t\t{ ' + ', '.join('{ %.4ff, %.4ff, %.4ff }' % tuple(j) for j in ph) + ' }' for ph in c['phases'])
    down = ', '.join('{ %s, %s }' % tuple('true' if d else 'false' for d in ph) for ph in c['down'])
    out.append('constexpr Cycle %s{ "%s", %.4ff, %.4ff, %d, %.1ff, {\n%s },\n\t{ %s } };' % (c['name'].upper(), c['name'], c['pace'], c['period'], c['strides'], c.get('way', 0), rows, down))
out += ['', '} // namespace physics::cycles', '']
print('\n'.join(out))
