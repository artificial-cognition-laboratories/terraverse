// Writes apps/game/src/sidecar/ops.h from src/runtime/wire/ops.ts. --check fails if it's stale.
import { Call, Event, Exit, Level, Op, PROTOCOL } from "../src/runtime"

const out = `${import.meta.dir}/../../game/src/sidecar/ops.h`

const cName = (key: string) => key.replace(/[.](\w)/g, (_, c: string) => c.toUpperCase()).replace(/^\w/, c => c.toUpperCase())
const enumOf = (name: string, values: Record<string, number>) =>
    `enum class ${name} : u8 {\n${Object.entries(values).map(([k, v]) => `\t${cName(k)} = ${v},`).join("\n")}\n};\n`

const text = `// Generated by apps/cli/scripts/ops.ts from apps/cli/src/runtime/wire/ops.ts. Don't edit.
#pragma once

#include "irrlichttypes.h"

namespace sidecar {

constexpr u32 PROTOCOL = ${PROTOCOL};
${Object.entries(Exit).map(([k, v]) => `constexpr int EXIT_${k.toUpperCase()} = ${v};`).join("\n")}

${enumOf("Op", Op)}
${enumOf("Call", Call)}
${enumOf("Event", Event)}
${enumOf("Level", Level)}
} // namespace sidecar
`

if (process.argv.includes("--check")) {
    const now = await Bun.file(out).text().catch(() => "")
    if (now !== text) {
        console.error("ops.h is stale: run `bun run ops` in apps/cli")
        process.exit(1)
    }
} else {
    await Bun.write(out, text)
    console.log(`wrote ${out}`)
}
