// Writes src/terra/project/typegen/globals.gen.ts from packages/types/*.d.ts: the engine's
// globals, built into terra as text. --check fails if it's stale.
const source = `${import.meta.dir}/../../../packages/types`
const out = `${import.meta.dir}/../src/terra/project/typegen/globals.gen.ts`
const NAMES = ["shared", "config", "server", "client"] as const

const entries = await Promise.all(NAMES.map(async name => `    ${name}: ${JSON.stringify(await Bun.file(`${source}/${name}.d.ts`).text())},`))
const text = `// Generated by apps/cli/scripts/globals.ts from packages/types. Don't edit: edit those.

/** Each declaration file, by the name it's written as in a project's .terra/types/. */
export const GLOBALS = {
${entries.join("\n")}
} as const

export type GlobalsName = keyof typeof GLOBALS
`

if (process.argv.includes("--check")) {
    if ((await Bun.file(out).text().catch(() => "")) !== text) {
        console.error("globals.gen.ts is stale: run `bun run gen` in apps/cli")
        process.exit(1)
    }
} else {
    await Bun.write(out, text)
    console.log(`wrote ${out}`)
}
