// The world being served, built on first use (server/terra.h). Read from the
// map settings (map_meta.txt), which exist while mods load, before the map
// generator does. Server Lua runs on one thread.
static std::string mapgenName(Server *server)
{
	std::string mg_name;
	server->getEmergeManager()->map_settings_mgr->getMapSetting("mg_name", &mg_name);
	return mg_name;
}

// The world's atlas: a terra world is a planet.
static const planet::Atlas &atlasOf(Server *server)
{
	const std::string mg_name = mapgenName(server);
	if (mg_name != "terra")
		throw LuaError("core.terra: this world isn't generated by terra (mg_name = " + mg_name + ")");
	if (const planet::Atlas *atlas = server->atlas())
		return *atlas;
	throw LuaError("core.terra: this terra world has no planet_atlas (made before sprint 30)");
}

// A body's world model (the home's: the world's own), built on first use.
static const World &world(Server *server, int body = planet::Atlas::HOME)
{
	std::vector<std::unique_ptr<World>> &worlds = server->terra().worlds;
	worlds.resize(atlasOf(server).bodies());
	std::unique_ptr<World> &built = worlds.at(body);
	if (!built)
		built = std::make_unique<World>(server->bodyWorlds().at(body).code);
	return *built;
}

// The body a position is on (seam's: the home; a position in seam has no
// place anyway)
static int bodyAt(Server *server, const v3f &pos)
{
	return atlasOf(server).bodyAt(planet::Atlas::moverNode(pos.X, pos.Y, pos.Z)).value_or(planet::Atlas::HOME);
}

// The world model of the body a position is on.
static const World &worldAt(Server *server, const v3f &pos)
{
	return world(server, bodyAt(server, pos));
}

// A step of the rivers on the weather's (sprint 115). Made on the first, from
// <world>/rivers.bin if it's there and this world's, else settled on the rain
// now; saved each new day, as the weather is.
static void stepRivers(ServerTerra::RiverState &r, const World &w, const weather::Weather &wx, double dt, const std::string &path)
{
	static const double YEAR_MEMORY = 365 * 86400.0, SPEED = 1.0; // m/s: water down a cell's run
	const terragen::Sphere &sphere = terragen::gridSphere();
	if (!r.network) {
		r.network = std::make_unique<rivers::Network>(
				rivers::Network::ofGrid(w.grid(), sphere, wx.layer().opts().planet.radius, SPEED, YEAR_MEMORY));
		std::ifstream in(path, std::ios::binary);
		if (in) {
			std::stringstream bytes;
			bytes << in.rdbuf();
			try {
				r.network->load(bytes.str());
				r.settled = true;
			} catch (const rivers::RiversError &e) {
				warningstream << "rivers: " << e.what() << "; settled afresh" << std::endl;
			}
		}
	}
	r.step++;
	std::vector<rivers::Shed> shed = rivers::runoff(wx, w.grid(), sphere, wx.now());
	std::vector<rivers::Forcing> &fs = r.forcings;
	fs.erase(std::remove_if(fs.begin(), fs.end(), [&](const rivers::Forcing &f) { return f.until <= wx.now(); }), fs.end());
	for (const rivers::Forcing &f : r.forcings)
		rivers::force(shed, sphere, f);
	if (!r.settled) {
		r.network->settle(rivers::climate(w.grid(), &wx, &sphere));
		r.settled = true;
	} else if (dt > 0) {
		r.network->step(dt, shed);
	}
	const double day = std::floor(wx.now() / 86400);
	if (day != r.day) {
		if (r.day >= 0) {
			std::ofstream out(path, std::ios::binary);
			out << r.network->save();
		}
		r.day = day;
	}
}

// The world's weather, opened on first use from <world>/weather.bin (or
// settled fresh) and stepped to the clock on every call; none while it's
// still being opened. Opening runs on a worker (a new world's settles a year
// of weather, rivers and all: seconds the server went on without, as a
// player joined); the first call starts it, a later one takes it once it's done.
static weather::Weather *weatherNow(Server *server)
{
	ServerTerra &t = server->terra();
	const World &w = world(server);
	double now = weather::clock(server->getEnv().getDayCount(), server->getEnv().getTimeOfDayF());
	try {
		if (!t.weather) {
			if (!t.weather_opening.valid()) {
				if (!t.matter)
					t.matter = std::make_unique<matter::Matter>(matter::Matter::load(porting::path_share + DIR_DELIM "matter"));
				const matter::Matter &m = *t.matter;
				const std::string weather_path = server->getWorldPath() + DIR_DELIM "weather.bin",
						rivers_path = server->getWorldPath() + DIR_DELIM "rivers.bin";
				t.weather_opening = std::async(std::launch::async, [&w, &m, weather_path, rivers_path, now] {
					auto state = std::make_shared<ServerTerra::RiverState>();
					weather::Weather::Opts opts{ w, m, weather_path };
					opts.each_step = [state, &w, rivers_path](const weather::Weather &wx, double dt) {
						stepRivers(*state, w, wx, dt, rivers_path);
					};
					ServerTerra::OpenedWeather out;
					out.weather = weather::Weather::open(opts, now);
					// a weather opened from its file with no step to take: the rivers start
					// from it all the same (from their own file, or settled on it)
					if (!state->network)
						stepRivers(*state, w, *out.weather, 0, rivers_path);
					out.rivers = state;
					return out;
				});
				return nullptr;
			}
			if (t.weather_opening.wait_for(std::chrono::seconds(0)) != std::future_status::ready)
				return nullptr;
			ServerTerra::OpenedWeather opened = t.weather_opening.get(); // (what it threw, thrown here)
			t.weather = std::move(opened.weather);
			t.rivers = std::move(opened.rivers);
		}
		t.weather->advance(now);
	} catch (const std::runtime_error &e) { // matter::MatterError, fluid::FluidError
		throw LuaError(std::string("core.terra.weather: ") + e.what());
	}
	return t.weather.get();
}

static double toDouble(fix v)
{
	return (double)v / ONE;
}

static double toDegrees(fix radians)
{
	return toDouble(radians) * 180.0 / M_PI;
}

// Into the table on top of the stack, at full precision (setfloatfield
// narrows to float).
static void setNumber(lua_State *L, const char *key, double value)
{
	lua_pushnumber(L, value);
	lua_setfield(L, -2, key);
}

// Where the engine's clock is in the year.
static fix hourNow(Server *server)
{
	return (fix)(server->getEnv().getTimeOfDayF() * ONE);
}

static Calendar today(Server *server, const World &w)
{
	return calendar(w.code().year, server->getEnv().getDayCount(), hourNow(server));
}

// A position's place on its body: the direction of the column it stands in
// (in the core too, and above the sky, the column under it). None for seam
// between tiles: no place.
static std::optional<Place> placeOf(Server *server, const v3f &pos)
{
	const planet::Atlas &atlas = atlasOf(server);
	// above the sky too: the column under it (Atlas::charted)
	const std::optional<planet::Atlas::Node> from = atlas.charted(planet::Atlas::moverNode(pos.X, pos.Y, pos.Z));
	if (!from)
		return std::nullopt;
	const std::optional<terragen::Atlas::Vec> p = atlas.point(*from, pos.X, pos.Y, pos.Z);
	if (!p)
		return std::nullopt;
	return planet::Atlas::direction(*p);
}

// The same where there must be one (a player, a sky): seam is an error.
static Place placeAt(Server *server, const v3f &pos)
{
	if (const std::optional<Place> d = placeOf(server, pos))
		return *d;
	throw LuaError("core.terra: the position is seam: on no column of the planet");
}

// core.terra.enabled() → whether terra generated this world (the Lab, for
// one, isn't); every other call raises where this is false.
int ModApiTerra::l_enabled(lua_State *L)
{
	NO_MAP_LOCK_REQUIRED;
	lua_pushboolean(L, mapgenName(getServer(L)) == "terra");
	return 1;
}

// core.terra.world() → { code, size, tilt, year_days, star, boundary, facing_star }:
// boundary, the height above the sea where space begins (terragen::SPACE_BOUNDARY);
// facing_star, the bodies (by id, the home as "") that keep one face to their star
int ModApiTerra::l_world(lua_State *L)
{
	NO_MAP_LOCK_REQUIRED;
	const WorldCode &c = world(getServer(L)).code();
	lua_createtable(L, 0, 8);
	setstringfield(L, -1, "code", c.text);
	setNumber(L, "boundary", terragen::SPACE_BOUNDARY);
	setintfield(L, -1, "size", c.size);
	setNumber(L, "tilt", toDouble(c.tilt));
	setintfield(L, -1, "year_days", c.year);
	setstringfield(L, -1, "star", c.star->id);
	lua_newtable(L);
	for (const terragen::BodyWorld &b : getServer(L)->bodyWorlds())
		if (b.code.processes.facing_star) {
			lua_pushboolean(L, true);
			lua_setfield(L, -2, (b.code.text == c.text ? "" : b.id.c_str()));
		}
	lua_setfield(L, -2, "facing_star");
	return 1;
}

// core.terra.calendar() → { year, day, date, year_days }: year and day count
// from 1; date runs 0..1 through the year (0 = northern spring equinox).
int ModApiTerra::l_calendar(lua_State *L)
{
	NO_MAP_LOCK_REQUIRED;
	const World &w = world(getServer(L));
	Calendar c = today(getServer(L), w);
	lua_createtable(L, 0, 4);
	setintfield(L, -1, "year", c.year + 1);
	setintfield(L, -1, "day", c.day + 1);
	setNumber(L, "date", toDouble(c.date));
	setintfield(L, -1, "year_days", w.code().year);
	return 1;
}

// A column's clock: the engine's as this body reads it, in its own days. Time
// is one across a spinning body; on one that faces its star it's where you are.
static terragen::System::Clock clockAt(Server *server, const v3f &pos)
{
	const terragen::BodyWorld &body = server->bodyWorlds().at(bodyAt(server, pos));
	std::unique_ptr<terragen::System> &system = server->terra().system;
	if (!system)
		system = std::make_unique<terragen::System>(terragen::SystemSpec::forWorld(world(server).code()));
	const double now = server->getEnv().getDayCount() + (double)server->getEnv().getTimeOfDayF();
	terragen::System::Clock c = system->clock(body.system, now, world(server).code().year);
	if (body.code.processes.facing_star) {
		const Dir d = placeAt(server, pos).dir();
		c.at += std::atan2((double)d.z, (double)d.x) / (2 * M_PI);
	}
	return c;
}

// The clock with its days taken out: `at` + `turns` × (days + time of day)
// holds across midnight, so the client works it out from the date it was sent.
static terragen::System::Clock clockFromStart(Server *server, const v3f &pos)
{
	const terragen::System::Clock now = clockAt(server, pos);
	const double days = server->getEnv().getDayCount();
	return { now.turns, now.at - now.turns * days };
}

static fix localHour(Server *server, const v3f &pos)
{
	const double h = clockAt(server, pos).hour(server->getEnv().getTimeOfDayF());
	return (fix)((h - std::floor(h)) * ONE);
}

// core.terra.hour(pos) → this body's time of day there, 0..1 (½ noon), and
// the hours in its day (nil on a body that faces its star: it has no day)
int ModApiTerra::l_hour(lua_State *L)
{
	NO_MAP_LOCK_REQUIRED;
	Server *server = getServer(L);
	const v3f pos = check_v3f(L, 1);
	const terragen::System::Clock c = clockAt(server, pos);
	const double h = c.hour(server->getEnv().getTimeOfDayF());
	lua_pushnumber(L, h - std::floor(h));
	if (c.turns == 0)
		lua_pushnil(L);
	else
		lua_pushnumber(L, 24 / std::abs(c.turns));
	return 2;
}

// core.terra.set_hour(pos, hour) → whether it could: runs the clock forward to
// the next time it's `hour` there. A body facing its star has only the one.
int ModApiTerra::l_set_hour(lua_State *L)
{
	Server *server = getServer(L);
	const v3f pos = check_v3f(L, 1);
	const double hour = luaL_checknumber(L, 2);
	luaL_argcheck(L, hour >= 0 && hour <= 1, 2, "hour must be between 0 and 1");
	const terragen::System::Clock c = clockAt(server, pos);
	if (c.turns == 0) {
		lua_pushboolean(L, false);
		return 1;
	}
	const double tod = server->getEnv().getTimeOfDayF();
	const double now = c.hour(tod);
	double ahead = (c.turns > 0 ? hour - now : now - hour);
	ahead -= std::floor(ahead);
	const double date = server->getEnv().getDayCount() + tod + ahead / std::abs(c.turns);
	const double whole = std::floor(date);
	server->setDate((u32)whole, (u32)((date - whole) * 24000));
	lua_pushboolean(L, true);
	return 1;
}

// core.terra.skip_days(days): the date on, the time of day as it was
int ModApiTerra::l_skip_days(lua_State *L)
{
	Server *server = getServer(L);
	const int days = luaL_checkinteger(L, 1);
	luaL_argcheck(L, days > 0, 1, "the date only goes forward");
	server->setDate(server->getEnv().getDayCount() + days, server->getEnv().getTimeOfDay());
	return 0;
}

// core.terra.sun(pos) → { latitude, declination, elevation (degrees),
// daylight (share of the day the sun is up), season, turns, at (this
// body's clock: the time of day is at + turns × the engine's) }
int ModApiTerra::l_sun(lua_State *L)
{
	NO_MAP_LOCK_REQUIRED;
	const v3f pos = check_v3f(L, 1);
	const World &w = worldAt(getServer(L), pos);
	fix latitude = latitudeOf(placeAt(getServer(L), pos).dir());
	Calendar c = today(getServer(L), w);
	fix decl = declination(w.code().tilt, c.date);
	const fix hour = localHour(getServer(L), pos);
	const fix up = elevation(latitude, decl, hour);
	terragen::System::Clock body_clock = clockFromStart(getServer(L), pos);
	body_clock.at -= std::floor(body_clock.at);
	lua_createtable(L, 0, 7);
	setNumber(L, "latitude", toDegrees(latitude));
	setNumber(L, "declination", toDegrees(decl));
	setNumber(L, "elevation", toDegrees(up));
	setNumber(L, "daylight", w.code().processes.facing_star ? (up > 0 ? 1 : 0) : toDouble(dayShare(latitude, decl)));
	setNumber(L, "turns", body_clock.turns);
	setNumber(L, "at", body_clock.at);
	setstringfield(L, -1, "season", SEASON_NAMES[(int)season(c.date, latitude)]);
	return 1;
}

// core.terra.climate(pos) → { temperature (°C, now), biome, heat, wet, rain
// (the year's, relative to the median over land), season (1 summer-wet .. −1 winter-wet) }:
// the climate of today's season at that column.
int ModApiTerra::l_climate(lua_State *L)
{
	NO_MAP_LOCK_REQUIRED;
	const v3f pos = check_v3f(L, 1);
	const World &w = worldAt(getServer(L), pos);
	const Place at = placeAt(getServer(L), pos);
	Calendar c = today(getServer(L), w);
	Column column = w.column(at, w.sunlight(at, c.date));
	lua_createtable(L, 0, 6);
	setNumber(L, "temperature", toDouble(w.temperature(at, c.date, localHour(getServer(L), pos))));
	setstringfield(L, -1, "biome", BIOME_NAMES[(int)column.biome]);
	setNumber(L, "heat", toDouble(column.heat));
	setNumber(L, "wet", toDouble(column.wet));
	setNumber(L, "rain", toDouble(column.rain));
	setNumber(L, "season", toDouble(column.season));
	return 1;
}

// core.terra.geology(pos) → { province, rock, ore, depth, plate, boundary,
// boundary_distance (blocks), volcano = { distance, active } | nil }: the
// ground at a point. `rock` and `ore` are the bedrock's at that depth below
// the surface (under the soil the game lays); above the ground, its surface rock.
int ModApiTerra::l_geology(lua_State *L)
{
	NO_MAP_LOCK_REQUIRED;
	const v3f pos = check_v3f(L, 1);
	const World &w = worldAt(getServer(L), pos);
	const Place at = placeAt(getServer(L), pos);
	const int32_t y = (int32_t)std::floor(pos.Y + 0.5f);
	Ground g = w.ground(at, w.sunlight(at, std::nullopt));
	Strata s = w.strata(at, g);
	int32_t depth = std::max(0, g.terrain + 1 - y); // the map generator's ground sits one above terragen's (water level 1)
	Rock rock = w.rock(s, depth, y);
	Ore ore = w.ore(s, rock, depth, y);
	const Grid &grid = w.grid();
	int32_t cell = w.cell(at);
	static const char *const BOUNDARIES[] = { "none", "convergent", "divergent", "transform" };

	lua_createtable(L, 0, 8);
	setstringfield(L, -1, "province", PROVINCE_NAMES[(int)s.province]);
	setstringfield(L, -1, "rock", ROCK_NAMES[(int)rock]);
	setstringfield(L, -1, "ore", ORE_NAMES[(int)ore]);
	setintfield(L, -1, "depth", depth);
	setintfield(L, -1, "plate", grid.tectonics.plate[cell]);
	setstringfield(L, -1, "boundary", BOUNDARIES[(int)grid.tectonics.boundary[cell]]);
	setintfield(L, -1, "boundary_distance", (int)((grid.tectonics.distance[cell] * w.cellBlocks() + HALF) >> FRAC));
	// the nearest volcano whose slopes reach here
	int32_t best = INT32_MAX;
	bool active = false;
	for (uint32_t k = grid.volcano_start[cell]; k < grid.volcano_start[cell + 1]; k++) {
		const Volcano &vo = grid.volcanoes[grid.volcano_list[k]];
		int32_t d = w.blocksBetween(at, vo.at);
		if (d < best) {
			best = d;
			active = vo.active;
		}
	}
	if (best != INT32_MAX) {
		lua_createtable(L, 0, 2);
		setintfield(L, -1, "distance", best);
		lua_pushboolean(L, active);
		lua_setfield(L, -2, "active");
		lua_setfield(L, -2, "volcano");
	}
	return 1;
}

// core.terra.cover(minp, maxp) → for every column of the area (x inner, z
// outer, from 1): { density, heat, wet, season, elevation, slope, fertility, bank, tree, roll } as parallel
// arrays, plus season (when the rain falls: 1 summer .. −1 winter) and
// fertility (0..1). What can grow and where trees stand; the game picks what grows.
// For map-generation callbacks: one call per chunk.
int ModApiTerra::l_cover(lua_State *L)
{
	NO_MAP_LOCK_REQUIRED;
	v3s16 a = check_v3s16(L, 1), b = check_v3s16(L, 2);
	if (b.X < a.X || b.Z < a.Z || (b.X - a.X + 1) * (b.Z - a.Z + 1) > 160 * 160)
		throw LuaError("core.terra.cover: the area must run min to max, at most 160 × 160 columns");
	const char *const NAMES[] = { "density", "heat", "wet", "season", "elevation", "slope", "fertility", "bank", "tree", "roll" };
	lua_createtable(L, 0, 10);
	int out = lua_gettop(L);
	for (const char *name : NAMES) {
		lua_createtable(L, (b.X - a.X + 1) * (b.Z - a.Z + 1), 0);
		lua_setfield(L, out, name);
	}
	int n = 1;
	const planet::Atlas &atlas = atlasOf(getServer(L));
	for (int32_t mz = a.Z; mz <= b.Z; mz++) {
		for (int32_t mx = a.X; mx <= b.X; mx++, n++) {
			// the storage column's place at its surface layer (seam and the
			// core are no column: nothing grows), on its body's world (an area
			// may take in slots of several)
			const World &w = world(getServer(L), atlas.bodyAt({ mx, 0, mz }).value_or(planet::Atlas::HOME));
			const std::optional<Place> at = atlas.place({ mx, 0, mz });
			Cover c{ 0, 0, 0, false, false, 0 };
			fix heat = 0, wet = 0, season = 0, elevation = 0;
			if (at) {
				Ground g = w.ground(*at, w.sunlight(*at, std::nullopt));
				c = w.cover(*at, g);
				heat = g.column.heat;
				wet = g.column.wet;
				season = g.column.season;
				elevation = g.column.elevation;
			}
			auto put = [&](const char *name) { lua_getfield(L, out, name); };
			put("density"); lua_pushnumber(L, toDouble(c.density)); lua_rawseti(L, -2, n); lua_pop(L, 1);
			put("heat"); lua_pushnumber(L, toDouble(heat)); lua_rawseti(L, -2, n); lua_pop(L, 1);
			put("wet"); lua_pushnumber(L, toDouble(wet)); lua_rawseti(L, -2, n); lua_pop(L, 1);
			put("season"); lua_pushnumber(L, toDouble(season)); lua_rawseti(L, -2, n); lua_pop(L, 1);
			put("fertility"); lua_pushnumber(L, toDouble(c.fertility)); lua_rawseti(L, -2, n); lua_pop(L, 1);
			put("elevation"); lua_pushnumber(L, toDouble(elevation)); lua_rawseti(L, -2, n); lua_pop(L, 1);
			put("slope"); lua_pushnumber(L, toDouble(c.slope)); lua_rawseti(L, -2, n); lua_pop(L, 1);
			put("bank"); lua_pushboolean(L, c.bank); lua_rawseti(L, -2, n); lua_pop(L, 1);
			put("tree"); lua_pushboolean(L, c.tree); lua_rawseti(L, -2, n); lua_pop(L, 1);
			put("roll"); lua_pushinteger(L, c.roll); lua_rawseti(L, -2, n); lua_pop(L, 1);
		}
	}
	return 1;
}

// A {lo, hi} pair from field `name` of the table at `idx`.
static void readRange(lua_State *L, int idx, const char *name, const std::string &species, double out[2])
{
	lua_getfield(L, idx, name);
	if (!lua_istable(L, -1))
		throw LuaError("core.terra.register_species '" + species + "': " + name + " must be { low, high }");
	for (int k = 0; k < 2; k++) {
		lua_rawgeti(L, -1, k + 1);
		if (!lua_isnumber(L, -1))
			throw LuaError("core.terra.register_species '" + species + "': " + name + " must be { low, high }");
		out[k] = lua_tonumber(L, -1);
		lua_pop(L, 1);
	}
	lua_pop(L, 1);
}

static std::string needString(lua_State *L, int idx, const char *name, const std::string &species)
{
	std::string out;
	if (!getstringfield(L, idx, name, out) || out.empty())
		throw LuaError("core.terra.register_species '" + species + "': " + name + " is required");
	return out;
}

// core.terra.register_species(def): a tree species. def = { name, heat = { lo, hi },
// wet = { lo, hi }, season = { lo, hi } (optional), bank, shore, on = { [block] = true, … },
// trunk, leaves, shape = an L-system as core.spawn_tree takes }. The climate is
// core.terra.cover's. In registration order, the first that fits doesn't win:
// core.terra.species picks among all that fit by the column's roll.
int ModApiTerra::l_register_species(lua_State *L)
{
	NO_MAP_LOCK_REQUIRED;
	luaL_checktype(L, 1, LUA_TTABLE);
	terra::SpeciesDef d{};
	d.name = needString(L, 1, "name", "?");
	ServerTerra &t = getServer(L)->terra();
	if (t.resolved)
		throw LuaError("core.terra.register_species: '" + d.name + "' comes after the species were first used (register them as mods load)");
	for (const terra::SpeciesDef &other : t.species)
		if (other.name == d.name)
			throw LuaError("core.terra.register_species: '" + d.name + "' is registered twice");
	readRange(L, 1, "heat", d.name, d.niche.heat);
	readRange(L, 1, "wet", d.name, d.niche.wet);
	lua_getfield(L, 1, "season");
	d.niche.seasonal = !lua_isnil(L, -1);
	lua_pop(L, 1);
	if (d.niche.seasonal)
		readRange(L, 1, "season", d.name, d.niche.season);
	d.niche.bank = getboolfield_default(L, 1, "bank", false);
	d.niche.shore = getboolfield_default(L, 1, "shore", false);
	d.trunk = needString(L, 1, "trunk", d.name);
	d.leaves = needString(L, 1, "leaves", d.name);

	lua_getfield(L, 1, "on");
	if (!lua_istable(L, -1))
		throw LuaError("core.terra.register_species '" + d.name + "': on must be a set of blocks");
	lua_pushnil(L);
	while (lua_next(L, -2)) {
		if (lua_type(L, -2) == LUA_TSTRING && lua_toboolean(L, -1))
			d.on.push_back(lua_tostring(L, -2));
		lua_pop(L, 1);
	}
	lua_pop(L, 1);
	std::sort(d.on.begin(), d.on.end());

	lua_getfield(L, 1, "shape");
	if (!lua_istable(L, -1))
		throw LuaError("core.terra.register_species '" + d.name + "': shape is required");
	int shape = lua_gettop(L);
	terra::Shape &s = d.shape;
	s.axiom = needString(L, shape, "axiom", d.name);
	getstringfield(L, shape, "rules_a", s.rules_a);
	getstringfield(L, shape, "rules_b", s.rules_b);
	getstringfield(L, shape, "rules_c", s.rules_c);
	getstringfield(L, shape, "rules_d", s.rules_d);
	s.trunk_type = "single";
	getstringfield(L, shape, "trunk_type", s.trunk_type);
	s.angle = getintfield_default(L, shape, "angle", 0);
	s.iterations = getintfield_default(L, shape, "iterations", 0);
	s.random_level = getintfield_default(L, shape, "random_level", 0);
	s.thin_branches = getboolfield_default(L, shape, "thin_branches", false);
	lua_pop(L, 1);

	t.species.push_back(std::move(d));
	return 0;
}

// core.terra.species(pos, ground) → the name of the tree species that grows at
// the column of pos on `ground` (a block name), or nil. Ask where
// core.terra.cover says a tree stands.
int ModApiTerra::l_species(lua_State *L)
{
	NO_MAP_LOCK_REQUIRED;
	Server *server = getServer(L);
	v3s16 p = check_v3s16(L, 1);
	const World &w = worldAt(server, v3f(p.X, p.Y, p.Z));
	std::string ground_name = luaL_checkstring(L, 2);
	const NodeDefManager *ndef = server->getNodeDefManager();
	content_t ground = ndef->getId(ground_name);
	if (ground == CONTENT_IGNORE)
		throw LuaError("core.terra.species: no block called '" + ground_name + "'");

	const std::vector<terra::Species> &species = server->terra().resolve(ndef);

	const std::optional<Place> at = placeOf(server, v3f(p.X, p.Y, p.Z));
	if (!at)
		return 0; // seam: no place, nothing grows
	Ground g = w.ground(*at, w.sunlight(*at, std::nullopt));
	const terra::Species *s = terra::choose(species, terra::spotAt(g, w.cover(*at, g)), ground);
	if (!s)
		return 0;
	lua_pushstring(L, s->name.c_str());
	return 1;
}

// The far view's generator of a body, built from what the server sends its
// clients.
static const far::Generator &surfaceGenerator(Server *server, int body)
{
	ServerTerra &t = server->terra();
	const planet::Atlas &atlas = atlasOf(server);
	t.surfaces.resize(atlas.bodies());
	std::unique_ptr<far::Generator> &g = t.surfaces.at(body);
	if (!g) {
		const std::optional<far::Horizon> h = server->horizon();
		if (!h)
			throw LuaError("core.terra: this world wasn't made by terra");
		g = std::make_unique<far::Generator>(*h, atlas, body);
	}
	return *g;
}

// core.terra.surface(pos) → { ground, top, water, liquid, trunk, canopy }: the
// column at pos as the generator makes it, without generating it. ground is
// the top solid block's y and top its name; water and liquid the surface of
// any water or lava over it; trunk and canopy, if a tree stands there,
// { low, high, name } (its blocks low to high; none on a planet). What the
// far view draws.
int ModApiTerra::l_surface(lua_State *L)
{
	NO_MAP_LOCK_REQUIRED;
	Server *server = getServer(L);
	v3s16 p = check_v3s16(L, 1);
	// a storage column of a region is one place on its body: the column the
	// generator builds there (its y the layer). No trees: they are planted
	// per map chunk, which a place's column isn't.
	const planet::Atlas &atlas = atlasOf(server);
	if (!atlas.place({ p.X, 0, p.Z }))
		throw LuaError("core.terra.surface: the column is seam: no place on the planet");
	const far::Cell column = surfaceGenerator(server, *atlas.bodyAt({ p.X, 0, p.Z })).column(p.X, p.Z);
	const far::Cell &c = column;
	const NodeDefManager *ndef = server->getNodeDefManager();
	lua_createtable(L, 0, 6);
	setNumber(L, "ground", c.ground);
	lua_pushstring(L, ndef->get(c.top).name.c_str());
	lua_setfield(L, -2, "top");
	if (c.water > c.ground) {
		setNumber(L, "water", c.water);
		lua_pushstring(L, ndef->get(c.liquid).name.c_str());
		lua_setfield(L, -2, "liquid");
	}
	for (auto [name, run] : { std::pair{ "trunk", &c.trunk }, std::pair{ "canopy", &c.canopy } }) {
		if (run->empty())
			continue;
		lua_createtable(L, 0, 3);
		setNumber(L, "low", run->low);
		setNumber(L, "high", run->high);
		lua_pushstring(L, ndef->get(run->node).name.c_str());
		lua_setfield(L, -2, "name");
		lua_setfield(L, -2, name);
	}
	return 1;
}

// core.terra.weather(pos) → { temperature (°C), humidity (0..1), cloud (0..1),
// precipitation (mm/h), snow, wind = { x, z } (m/s, east and north),
// pressure (hPa), ash (0..1), soil (how wet the ground is, 0..1), events = { name, … }, atmosphere }: the
// weather now at a point. The world's atmosphere moves on its own
// (src/fluid); this reads it. `atmosphere` false: the point is on a body
// whose air isn't simulated (still, dry, its climate's temperature).
int ModApiTerra::l_weather(lua_State *L)
{
	NO_MAP_LOCK_REQUIRED;
	Server *server = getServer(L);
	const v3f pos = check_v3f(L, 1);
	const int body = bodyAt(server, pos);
	const World &w = world(server, body);
	const Place at = placeAt(getServer(L), pos);
	const int32_t y = (int32_t)std::floor(pos.Y + 0.5f);
	fluid::Sample s{};
	// (only a home with seas has the moving air src/fluid models: water's, Earth's)
	const bool moving = body == planet::Atlas::HOME && w.code().processes.water && !w.code().processes.facing_star; // (src/fluid's bands are round a spin)
	if (moving) {
		const weather::Weather *wx = weatherNow(server);
		if (!wx)
			return 0; // (still settling as the world opens: nil, nothing to tell yet)
		s = wx->sample(at, y, wx->now());
	} else {
		// TEMP: 2026-10-29 only the home's air moves (src/fluid); another
		// body's is still and dry at its climate's temperature until its
		// own atmosphere (sprint 41)
		s.temperature = toDouble(w.temperature(at, today(server, w).date, hourNow(server))) + 273.15;
		s.pressure = server->bodyWorlds().at(body).surroundings.pressure; // its card's (none on the Moon)
	}
	lua_createtable(L, 0, 10);
	lua_pushboolean(L, moving);
	lua_setfield(L, -2, "atmosphere");
	setNumber(L, "temperature", s.temperature - 273.15);
	setNumber(L, "humidity", s.humidity);
	setNumber(L, "cloud", s.cloud);
	setNumber(L, "precipitation", s.precipitation);
	lua_pushboolean(L, s.snow);
	lua_setfield(L, -2, "snow");
	lua_createtable(L, 0, 2);
	setNumber(L, "x", s.wind_u);
	setNumber(L, "z", s.wind_v);
	lua_setfield(L, -2, "wind");
	setNumber(L, "pressure", s.pressure / 100);
	setNumber(L, "ash", s.ash);
	setNumber(L, "soil", s.soil);
	lua_newtable(L);
	int n = 1;
	for (int e = 0; e < (int)fluid::Event::Count; e++)
		if (s.events & (1u << e)) {
			lua_pushstring(L, fluid::EVENT_NAMES[e]);
			lua_rawseti(L, -2, n++);
		}
	lua_setfield(L, -2, "events");
	return 1;
}

// core.terra.river(pos) → nil, or { discharge (m³/s, its planet's), local
// (m³/s its channel carries in the blocks), ratio (its flow now
// against its mean), rise (blocks over or under the water as generated),
// speed (nodes/s), to_sea (days its water takes to reach the sea), lake }: the river or lake at a column, as the weather now
// fills it (sprint 115). Nil where terragen puts none, and while the
// rivers settle with the weather as a world opens.
int ModApiTerra::l_river(lua_State *L)
{
	NO_MAP_LOCK_REQUIRED;
	Server *server = getServer(L);
	const v3f pos = check_v3f(L, 1);
	if (bodyAt(server, pos) != planet::Atlas::HOME)
		return 0;
	const World &w = world(server);
	const Place at = placeAt(server, pos);
	const terragen::Ground g = w.ground(at, w.sunlight(at, std::nullopt));
	if (g.kind != terragen::Water::River && g.kind != terragen::Water::Lake)
		return 0;
	weatherNow(server);
	ServerTerra &t = server->terra();
	if (!t.rivers)
		return 0; // (still settling with the weather as the world opens)
	const rivers::Flow f = rivers::flowAt(*t.rivers->network, terragen::gridSphere(), g, at);
	lua_createtable(L, 0, 6);
	setNumber(L, "discharge", f.discharge);
	setNumber(L, "to_sea", f.to_sea / 86400);
	setNumber(L, "local", f.local);
	lua_pushboolean(L, f.stream);
	lua_setfield(L, -2, "stream");
	if (f.stream)
		setNumber(L, "drains", f.share); // in its cell's areas
	setNumber(L, "ratio", f.ratio);
	setNumber(L, "rise", f.rise);
	setNumber(L, "speed", f.speed);
	lua_pushboolean(L, g.kind == terragen::Water::Lake);
	lua_setfield(L, -2, "lake");
	return 1;
}

// core.terra.force_rivers(pos, radius_km, hours, rain_mm_h): rains
// rain_mm_h on saturated ground (0: a drought, nothing shed) over the grid's
// cells within radius_km of pos for the next `hours` of game time, in place
// of the weather's (sprint 115: to watch a river answer). radius_km 0 clears
// every forcing.
int ModApiTerra::l_force_rivers(lua_State *L)
{
	NO_MAP_LOCK_REQUIRED;
	Server *server = getServer(L);
	const v3f pos = check_v3f(L, 1);
	const double radius_km = luaL_checknumber(L, 2), hours = luaL_checknumber(L, 3), rain = luaL_checknumber(L, 4);
	ServerTerra &t = server->terra();
	const weather::Weather *opened = weatherNow(server);
	if (!opened || !t.rivers)
		throw LuaError("core.terra.force_rivers: the rivers are still settling (the world's just opened)");
	if (radius_km <= 0) {
		t.rivers->forcings.clear();
		return 0;
	}
	if (hours <= 0 || rain < 0)
		throw LuaError("core.terra.force_rivers: hours must be over 0 and rain at least 0");
	if (bodyAt(server, pos) != planet::Atlas::HOME)
		throw LuaError("core.terra.force_rivers: only the home world has rivers");
	const weather::Weather &wx = *opened;
	rivers::Forcing f;
	f.centre = placeAt(server, pos);
	f.radius = radius_km * 1000 / wx.layer().opts().planet.radius;
	f.rain = rain / 1000 / 3600;
	f.until = wx.now() + hours * 3600;
	t.rivers->forcings.push_back(f);
	return 0;
}

// The way a river runs at a held node, in the map's x and z: down its run
// (terragen's blocks along it, measured a few blocks either side), as a byte
// 1..255 round from +x toward +z; 0 for a lake, or where it can't be told.
static u8 riverWay(Server *server, const World &w, v3s16 node)
{
	static const s16 D = 4;
	auto along = [&](s16 dx, s16 dz, int32_t cell) -> std::optional<double> {
		const std::optional<Place> p = placeOf(server, intToFloat(node + v3s16(dx, 0, dz), 1));
		if (!p)
			return std::nullopt;
		const terragen::Ground g = w.ground(*p, w.sunlight(*p, std::nullopt));
		if (g.kind != terragen::Water::River || (cell >= 0 && g.river_cell != cell))
			return std::nullopt;
		return g.river_along;
	};
	const std::optional<Place> here = placeOf(server, intToFloat(node, 1));
	if (!here)
		return 0;
	const terragen::Ground g = w.ground(*here, w.sunlight(*here, std::nullopt));
	if (g.kind != terragen::Water::River || g.river_cell < 0)
		return 0;
	// the gradient each way, from both sides where both are this run, else one
	auto slope = [&](s16 dx, s16 dz) {
		const std::optional<double> a = along(-dx, -dz, g.river_cell), b = along(dx, dz, g.river_cell);
		if (a && b)
			return (*b - *a) / (2 * D);
		if (b)
			return (*b - g.river_along) / D;
		if (a)
			return (g.river_along - *a) / D;
		return 0.0;
	};
	const double gx = slope(D, 0), gz = slope(0, D);
	if (gx == 0 && gz == 0)
		return 0;
	const double turn = std::atan2(gz, gx) / (2 * M_PI); // −½..½
	return (u8)(1 + (long)std::lround((turn < 0 ? turn + 1 : turn) * 254) % 255);
}

double terraRiverDischarge(Server *server, v3s16 node)
{
	ServerTerra &t = server->terra();
	if (!t.rivers || mapgenName(server) != "terra")
		return 0;
	const std::optional<Place> place = placeOf(server, intToFloat(node, 1));
	if (!place)
		return 0;
	const World &w = world(server);
	const terragen::Ground g = w.ground(*place, w.sunlight(*place, std::nullopt));
	if (g.kind != terragen::Water::River)
		return 0;
	// and what lakes' streams bring it, run into it upstream of here
	double brought = 0;
	auto joins = t.river_joins.find(g.river_cell);
	if (joins != t.river_joins.end())
		for (const auto &[along, q] : joins->second)
			if (along < g.river_along)
				brought += q;
	return rivers::flowAt(*t.rivers->network, terragen::gridSphere(), g, *place).local + brought;
}

std::pair<s32, s32> terraRiverRun(Server *server, v3s16 node)
{
	if (mapgenName(server) != "terra")
		return { -1, 0 };
	const std::optional<Place> place = placeOf(server, intToFloat(node, 1));
	if (!place)
		return { -1, 0 };
	const World &w = world(server);
	const terragen::Ground g = w.ground(*place, w.sunlight(*place, std::nullopt));
	return g.kind == terragen::Water::River ? std::pair<s32, s32>{ g.river_cell, g.river_along } : std::pair<s32, s32>{ -1, 0 };
}

std::pair<double, double> terraLakeWeather(Server *server, v3s16 node)
{
	const v3f pos = intToFloat(node, 1);
	if (mapgenName(server) != "terra" || bodyAt(server, pos) != planet::Atlas::HOME)
		return { 0, 0 };
	const std::optional<Place> at = placeOf(server, pos);
	if (!at)
		return { 0, 0 };
	const weather::Weather *wx = weatherNow(server);
	if (!wx)
		return { 0, 0 }; // (none yet: it settles as the world opens)
	const fluid::Sample s = wx->sample(*at, node.Y, wx->now());
	return { s.precipitation, weather::openWaterEvaporation(s) };
}

s32 terraGeneratedTop(Server *server, s32 x, s32 z)
{
	// the column as the generator makes it (the far view's: check:far holds it to the blocks)
	if (mapgenName(server) != "terra")
		return rivers::Basin::UNKNOWN;
	const planet::Atlas &atlas = atlasOf(server);
	const std::optional<int> body = atlas.bodyAt({ (s16)x, 0, (s16)z });
	if (!atlas.place({ (s16)x, 0, (s16)z }) || !body)
		return rivers::Basin::UNKNOWN;
	const far::Cell c = surfaceGenerator(server, *body).column((s16)x, (s16)z);
	return std::max(c.ground, c.water) + 1;
}

// core.terra.lake(pos) → nil, or { level, spill (blocks), area (m²), inflow
// (m³/s), outflow (m³/s over its rim), columns, capped, spills_in (s till it's full at this inflow; 0
// spilling, nil draining or with nothing coming in), rain and evaporation
// (mm/h over it), closed (its losses balance its inflow under its spill),
// balance (the level they balance at, when closed) }: the lake over the
// column at pos (sprint 115)
int ModApiTerra::l_lake(lua_State *L)
{
	NO_MAP_LOCK_REQUIRED;
	Server *server = getServer(L);
	const v3s16 p = floatToInt(check_v3f(L, 1), 1);
	for (const ServerTerra::Lake &lake : server->terra().lakes) {
		if (!lake.basin)
			continue;
		const bool over = lake.wet.count(((s64)p.X << 32) | (u32)(s32)p.Z) > 0 ||
				std::any_of(lake.basin->columns().begin(), lake.basin->columns().end(),
						[&](const rivers::Basin::Column &c) { return c.x == p.X && c.z == p.Z; });
		if (!over)
			continue;
		lua_createtable(L, 0, 6);
		setNumber(L, "level", lake.level);
		setNumber(L, "spill", lake.basin->dammed() ? lake.basin->spill() : lake.level0);
		setNumber(L, "area", lake.basin->area(lake.level));
		setNumber(L, "inflow", lake.inflow);
		setNumber(L, "outflow", lake.outflow);
		// its streams: { path = { {x, y, z}, … } (water's on y), q (m³/s), fills (it runs into a lake) }
		lua_createtable(L, (int)lake.streams.size(), 0);
		for (size_t i = 0; i < lake.streams.size(); i++) {
			const ServerTerra::Lake::Stream &st = lake.streams[i];
			lua_createtable(L, 0, 3);
			lua_createtable(L, (int)st.path.size(), 0);
			for (size_t k = 0; k < st.path.size(); k++) {
				push_v3s16(L, v3s16(st.path[k][0], st.path[k][2], st.path[k][1]));
				lua_rawseti(L, -2, (int)k + 1);
			}
			lua_setfield(L, -2, "path");
			setNumber(L, "q", st.q);
			lua_pushboolean(L, st.fills.has_value());
			lua_setfield(L, -2, "fills");
			lua_rawseti(L, -2, (int)i + 1);
		}
		lua_setfield(L, -2, "streams");
		setNumber(L, "fed", lake.fed);
		if (lake.basin->dammed()) {
			lua_createtable(L, 0, 2);
			setNumber(L, "x", lake.basin->outX());
			setNumber(L, "z", lake.basin->outZ());
			lua_setfield(L, -2, "out"); // where its flood ran off
		}
		setNumber(L, "columns", (double)lake.basin->columns().size());
		lua_pushboolean(L, lake.basin->capped());
		lua_setfield(L, -2, "capped");
		const rivers::Basin &b = *lake.basin;
		setNumber(L, "rain", lake.rain);
		setNumber(L, "evaporation", lake.evaporation);
		const double balance = terraLakeBalance(lake);
		lua_pushboolean(L, b.dammed() && balance < b.spill());
		lua_setfield(L, -2, "closed");
		if (b.dammed() && balance < b.spill())
			setNumber(L, "balance", balance);
		if (b.dammed() && lake.level >= b.spill()) {
			setNumber(L, "spills_in", 0);
		} else if (b.dammed() && balance >= b.spill()) {
			// at what comes in less what goes off its surface now
			const double net = lake.inflow + (lake.rain - lake.evaporation) / 3.6e6 * std::max(1.0, b.area(lake.level));
			if (net > 0)
				setNumber(L, "spills_in", (b.volume(b.spill()) - b.volume(lake.level)) / net);
		}
		return 1;
	}
	return 0;
}

void terraSendRivers(Server *server)
{
	static const int AROUND = 3; // map blocks each way, across; 2 down, 1 up
	if (mapgenName(server) != "terra")
		return;
	ServerTerra &t = server->terra();
	const World &w = world(server);
	// (the weather's opened from here as the server starts, before anyone
	// asks: where it moves, as core.terra.weather has it)
	if (w.code().processes.water && !w.code().processes.facing_star)
		weatherNow(server);
	if (!t.rivers)
		return; // no weather yet: rivers stand as generated
	ServerMap &map = server->getEnv().getServerMap();
	// A map block's river: its held water found once, its flow read again
	// each rivers step (and its flood over its banks set by it); nullptr for
	// a block never loaded
	auto read = [&](v3s16 bp) -> ServerTerra::RiverBlock * {
		MapBlock *block = map.getBlockNoCreateNoEx(bp);
		auto known = t.river_blocks.find(bp);
		if (!block && known == t.river_blocks.end())
			return nullptr;
		ServerTerra::RiverBlock &rb = t.river_blocks[bp];
		if (known == t.river_blocks.end()) {
			// looked at once: generated water is held from the start
			for (s16 i = 0; i < MAP_BLOCKSIZE * MAP_BLOCKSIZE * MAP_BLOCKSIZE && !rb.held; i++) {
				const v3s16 rel(i % MAP_BLOCKSIZE, (i / MAP_BLOCKSIZE) % MAP_BLOCKSIZE, i / (MAP_BLOCKSIZE * MAP_BLOCKSIZE));
				const u8 param2 = block->getNodeNoCheck(rel).getParam2();
				if ((param2 & fill::HELD) && !(param2 & fill::LAKE)) // (a river's own, not a lake's over it)
					rb.held = bp * MAP_BLOCKSIZE + rel;
			}
			if (rb.held)
				rb.way = riverWay(server, w, *rb.held);
		}
		if (rb.held && rb.read_at != t.rivers->step) {
			rb.read_at = t.rivers->step;
			const std::optional<Place> place = placeOf(server, intToFloat(*rb.held, 1));
			const terragen::Ground g = place ? w.ground(*place, w.sunlight(*place, std::nullopt)) : terragen::Ground{};
			if (place && (g.kind == terragen::Water::River || g.kind == terragen::Water::Lake)) {
				const rivers::Flow f = rivers::flowAt(*t.rivers->network, terragen::gridSphere(), g, *place);
				rb.rise = (s16)std::lround(f.rise * 16);
				rb.speed = (u8)std::clamp<long>(std::lround(f.speed * 40), 0, 255);
				terraFlood(server, *rb.held, f.surge);
			}
		}
		return &rb;
	};
	// the Live blocks (round players, and kept loaded): their rivers run, and flood
	for (const v3s16 &bp : server->getEnv().getActiveBlocks())
		read(bp);
	std::unordered_map<u16, bool> connected;
	for (RemotePlayer *player : server->getEnv().getPlayers()) {
		PlayerSAO *sao = player->getPlayerSAO();
		if (!sao || player->getPeerId() == PEER_ID_INEXISTENT)
			continue;
		const u16 peer = player->getPeerId();
		connected[peer] = true;
		std::unordered_map<v3s16, u32> &sent = t.river_sent[peer];
		std::vector<std::tuple<v3s16, s16, u8, u8>> out;
		const v3s16 at = getNodeBlockPos(floatToInt(sao->getBasePosition(), BS));
		for (s16 dz = -AROUND; dz <= AROUND; dz++)
			for (s16 dx = -AROUND; dx <= AROUND; dx++)
				for (s16 dy = -2; dy <= 1; dy++) {
					const v3s16 bp = at + v3s16(dx, dy, dz);
					ServerTerra::RiverBlock *rb = read(bp);
					if (!rb)
						continue;
					// a lake's top: still, at its level
					if (const std::optional<s16> lake = terraLakeRise(server, bp)) {
						const u32 packed = ((u32)(u16)*lake << 16) | 0xFFFF; // (no river runs 255 at way 255)
						auto was = sent.find(bp);
						if (was == sent.end() || was->second != packed) {
							sent[bp] = packed;
							out.emplace_back(bp, *lake, 0, 0);
						}
						continue;
					}
					if (!rb->held)
						continue;
					const u32 packed = ((u32)(u16)rb->rise << 16) | ((u32)rb->speed << 8) | rb->way;
					auto was = sent.find(bp);
					if (was == sent.end() || was->second != packed) {
						sent[bp] = packed;
						out.emplace_back(bp, rb->rise, rb->speed, rb->way);
					}
				}
		if (!out.empty())
			server->sendRivers(peer, out);
	}
	for (auto it = t.river_sent.begin(); it != t.river_sent.end();)
		it = connected.count(it->first) ? std::next(it) : t.river_sent.erase(it);
}

// core.terra.soil_points() → { { sand, silt, clay, organic }, … } (index + 1 =
// the soil block's param2 + 1): the compositions a soil block can hold. Pure:
// works on any world (the game registers its soil from it).
int ModApiTerra::l_soil_points(lua_State *L)
{
	NO_MAP_LOCK_REQUIRED;
	lua_createtable(L, SOIL_POINTS, 0);
	for (int32_t i = 0; i < SOIL_POINTS; i++) {
		Soil s = soilPoint((uint8_t)i);
		lua_createtable(L, 0, 4);
		setNumber(L, "sand", toDouble(s.sand));
		setNumber(L, "silt", toDouble(s.silt));
		setNumber(L, "clay", toDouble(s.clay));
		setNumber(L, "organic", toDouble(s.organic));
		lua_rawseti(L, -2, i + 1);
	}
	return 1;
}

// core.terra.soil_kinds() → { parents = { "granitic", … }, stony = { { name =
// "" | "stony" | …, stones = share }, … } } (sprint 111): the soil blocks the
// generator places, one per parent and stony class; the game registers each
// as "tf_world:soil_<parent>[_<stony>]" with a mapgen alias of that name.
int ModApiTerra::l_soil_kinds(lua_State *L)
{
	NO_MAP_LOCK_REQUIRED;
	lua_createtable(L, 0, 2);
	lua_createtable(L, (int)SoilParent::Count, 0);
	for (int p = 0; p < (int)SoilParent::Count; p++) {
		lua_pushstring(L, SOIL_PARENT_NAMES[p]);
		lua_rawseti(L, -2, p + 1);
	}
	lua_setfield(L, -2, "parents");
	lua_createtable(L, SOIL_STONY, 0);
	for (int k = 0; k < SOIL_STONY; k++) {
		lua_createtable(L, 0, 2);
		lua_pushstring(L, SOIL_STONY_NAMES[k]);
		lua_setfield(L, -2, "name");
		setNumber(L, "stones", toDouble(soilStonesOf(k)));
		lua_rawseti(L, -2, k + 1);
	}
	lua_setfield(L, -2, "stony");
	return 1;
}

// core.terra.land(minp, maxp) → for every node of the area (as VoxelArea
// indexes it: x inner, then y, then z, from 1) the name of the block the
// generator places there on an atlas planet (terra::AtlasLand: what the far
// view draws), or false where it stores no cell (seam). Before the game's
// own planting. At most 2²⁴ nodes; raises on another world.
int ModApiTerra::l_land(lua_State *L)
{
	NO_MAP_LOCK_REQUIRED;
	Server *server = getServer(L);
	const planet::Atlas &atlas = atlasOf(server);
	const v3s16 a = check_v3s16(L, 1), b = check_v3s16(L, 2);
	if (b.X < a.X || b.Y < a.Y || b.Z < a.Z)
		throw LuaError("core.terra.land: the area must run min to max");
	const s64 sx = b.X - a.X + 1, sy = b.Y - a.Y + 1, sz = b.Z - a.Z + 1;
	if (sx * sy * sz > (1 << 24))
		throw LuaError("core.terra.land: at most 2^24 nodes at once");
	const NodeDefManager *ndef = server->getNodeDefManager();
	// a reader a body (an area may take in slots of several), each column by its body's
	std::vector<std::optional<terra::AtlasLand::Reader>> readers(atlas.bodies());
	lua_createtable(L, (int)(sx * sy * sz), 0);
	// column by column, bottom up: the reader keeps a column while it lasts
	for (s16 z = a.Z; z <= b.Z; z++)
		for (s16 x = a.X; x <= b.X; x++) {
			const int body = atlas.bodyAt({ x, 0, z }).value_or(planet::Atlas::HOME); // seam reads as seam in any
			std::optional<terra::AtlasLand::Reader> &reader = readers[body];
			if (!reader)
				reader.emplace(surfaceGenerator(server, body).land());
			for (s16 y = a.Y; y <= b.Y; y++) {
				const std::optional<MapNode> n = reader->node({ x, y, z });
				if (n)
					lua_pushstring(L, ndef->get(*n).name.c_str());
				else
					lua_pushboolean(L, false);
				lua_rawseti(L, -2, (int)((z - a.Z) * sy * sx + (y - a.Y) * sx + (x - a.X) + 1));
			}
		}
	return 1;
}

// core.terra.place(pos) → { x, y, z }: the place on its body a position's
// column is, as the world model takes it: a direction from the centre as
// integers, 2^30 a unit (terragen::Place), so a check can ask terragen
// about exactly the same place.
int ModApiTerra::l_place(lua_State *L)
{
	NO_MAP_LOCK_REQUIRED;
	const Place d = placeAt(getServer(L), check_v3f(L, 1));
	lua_createtable(L, 0, 3);
	setintfield(L, -1, "x", d.x);
	setintfield(L, -1, "y", d.y);
	setintfield(L, -1, "z", d.z);
	return 1;
}

// core.terra.seam(pos) → whether a position is seam: on no column of the
// planet, so it has no place (core.terra.place refuses it)
int ModApiTerra::l_seam(lua_State *L)
{
	NO_MAP_LOCK_REQUIRED;
	lua_pushboolean(L, !placeOf(getServer(L), check_v3f(L, 1)).has_value());
	return 1;
}

void ModApiTerra::Initialize(lua_State *L, int top)
{
	lua_newtable(L);
	int terra = lua_gettop(L);
	luaL_Reg functions[] = {
		{ "enabled", l_enabled },
		{ "world", l_world },
		{ "calendar", l_calendar },
		{ "sun", l_sun },
		{ "hour", l_hour },
		{ "set_hour", l_set_hour },
		{ "skip_days", l_skip_days },
		{ "climate", l_climate },
		{ "geology", l_geology },
		{ "cover", l_cover },
		{ "register_species", l_register_species },
		{ "species", l_species },
		{ "surface", l_surface },
		{ "weather", l_weather },
		{ "river", l_river },
		{ "force_rivers", l_force_rivers },
		{ "lake", l_lake },
		{ "soil_points", l_soil_points },
		{ "soil_kinds", l_soil_kinds },
		{ "place", l_place },
		{ "seam", l_seam },
		{ "land", l_land },
	};
	for (const luaL_Reg &f : functions) {
		lua_pushcfunction(L, f.func);
		lua_setfield(L, terra, f.name);
	}
	lua_setfield(L, top, "terra");
}
